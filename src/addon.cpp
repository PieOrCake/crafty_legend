void AddonLoad(AddonAPI_t* aApi) {
    APIDefs = aApi;
    ImGui::SetCurrentContext((ImGuiContext*)APIDefs->ImguiContext);
    ImGui::SetAllocatorFunctions((void* (*)(size_t, void*))APIDefs->ImguiMalloc, (void(*)(void*, void*))APIDefs->ImguiFree);

    // Initialize data manager
    if (!CraftyLegend::DataManager::Initialize()) {
        APIDefs->Log(LOGL_CRITICAL, "CraftyLegend", "Failed to initialize data manager");
    } else {
        APIDefs->Log(LOGL_INFO, "CraftyLegend", "Data manager initialized successfully");
        // Log currency stats for debugging
        {
            const auto& currencies = CraftyLegend::DataManager::GetCurrencies();
            int withIcon = 0;
            for (const auto& c : currencies) {
                if (!c.icon.empty()) withIcon++;
            }
            std::stringstream msg;
            msg << "[CurrIcon] Loaded " << currencies.size() << " currencies, " << withIcon << " with icon URLs";
            g_DebugLog.push_back(msg.str());
        }
    }

    // Initialize icon manager
    CraftyLegend::IconManager::Initialize(APIDefs);
    
    // Load display settings and persisted state
    LoadDisplaySettings();
    LoadLastUpdated();

    CraftyLegend::GW2API::LoadPriceData();
    CraftyLegend::DataManager::LoadFavourites();

    // Subscribe to Hoard & Seek events
    APIDefs->Events_Subscribe(EV_HOARD_DATA_UPDATED, OnHoardDataUpdated);
    APIDefs->Events_Subscribe(CL_ITEM_RESPONSE, OnHoardItemResponse);
    APIDefs->Events_Subscribe(CL_WALLET_RESPONSE, OnHoardWalletResponse);
    APIDefs->Events_Subscribe(CL_ACHIEVEMENT_RESPONSE, OnAchievementResponse);
    APIDefs->Events_Subscribe(CL_MASTERY_RESPONSE, OnMasteryResponse);
    APIDefs->Events_Subscribe(EV_HOARD_FETCH_PROGRESS, OnHoardFetchProgress);
    APIDefs->Events_Subscribe(EV_HOARD_FETCH_ERROR, OnHoardFetchError);
    APIDefs->Events_Subscribe(EV_HOARD_PONG, OnHoardPong);
    APIDefs->Events_Subscribe(CL_ACCOUNTS_RESPONSE, OnAccountsResponse);
    APIDefs->Events_Subscribe(EV_MUMBLE_IDENTITY_UPDATED, OnMumbleIdentityUpdated);
    APIDefs->Events_Subscribe(EV_HOARD_ACCOUNTS_CHANGED, OnAccountsChanged);
    APIDefs->Log(LOGL_INFO, "CraftyLegend", "Subscribed to Hoard & Seek events");

    // Get MumbleLink data pointer for identity polling fallback
    g_MumbleData = static_cast<Mumble::Data*>(APIDefs->DataLink_Get(DL_MUMBLE_LINK));

    // Ping H&S to get current state (timestamps, has_data) if already loaded
    APIDefs->Events_Raise(EV_HOARD_PING, nullptr);
    g_StartupPingRetryTime = std::chrono::steady_clock::now() + std::chrono::seconds(2);

    // Register render functions
    APIDefs->GUI_Register(RT_Render, AddonRender);
    APIDefs->GUI_Register(RT_OptionsRender, AddonOptions);

    // Register keybind
    APIDefs->InputBinds_RegisterWithString("KB_CRAFTY_TOGGLE", ProcessKeybind, "CTRL+SHIFT+L");

    // Load anvil icon textures from embedded PNG data
    APIDefs->Textures_LoadFromMemory(TEX_ANVIL, (void*)ICON_ANVIL, ICON_ANVIL_size, nullptr);
    APIDefs->Textures_LoadFromMemory(TEX_ANVIL_HOVER, (void*)ICON_ANVIL_HOVER, ICON_ANVIL_HOVER_size, nullptr);

    // Register quick access shortcut (anvil icon toggles window via keybind)
    if (g_ShowQAIcon) {
        APIDefs->QuickAccess_Add(QA_ID, TEX_ANVIL, TEX_ANVIL_HOVER, "KB_CRAFTY_TOGGLE", "CraftyLegend");
    }

    APIDefs->Log(LOGL_INFO, "CraftyLegend", "Addon loaded successfully");
}

void AddonUnload() {
    // Unsubscribe from Hoard & Seek events
    APIDefs->Events_Unsubscribe(EV_HOARD_DATA_UPDATED, OnHoardDataUpdated);
    APIDefs->Events_Unsubscribe(CL_ITEM_RESPONSE, OnHoardItemResponse);
    APIDefs->Events_Unsubscribe(CL_WALLET_RESPONSE, OnHoardWalletResponse);
    APIDefs->Events_Unsubscribe(CL_ACHIEVEMENT_RESPONSE, OnAchievementResponse);
    APIDefs->Events_Unsubscribe(CL_MASTERY_RESPONSE, OnMasteryResponse);
    APIDefs->Events_Unsubscribe(EV_HOARD_FETCH_PROGRESS, OnHoardFetchProgress);
    APIDefs->Events_Unsubscribe(EV_HOARD_FETCH_ERROR, OnHoardFetchError);
    APIDefs->Events_Unsubscribe(EV_HOARD_PONG, OnHoardPong);
    APIDefs->Events_Unsubscribe(CL_ACCOUNTS_RESPONSE, OnAccountsResponse);
    APIDefs->Events_Unsubscribe(EV_MUMBLE_IDENTITY_UPDATED, OnMumbleIdentityUpdated);
    APIDefs->Events_Unsubscribe(EV_HOARD_ACCOUNTS_CHANGED, OnAccountsChanged);

    CraftyLegend::IconManager::Shutdown();
    APIDefs->QuickAccess_Remove(QA_ID);
    APIDefs->GUI_Deregister(AddonOptions);
    APIDefs->GUI_Deregister(AddonRender);
    
    // Save final scroll positions before shutdown
    CraftyLegend::DataManager::SetSessionScrollState(g_TrackedScrollX, g_TrackedCol0ScrollY, g_TrackedColScrollY);
    CraftyLegend::DataManager::SaveSession();
    
    // Cleanup data manager
    CraftyLegend::DataManager::Shutdown();
    
    APIDefs = nullptr;
}

void ProcessKeybind(const char* aIdentifier, bool aIsRelease) {
    if (aIsRelease) return;  // Only handle key press, not release
    
    if (strcmp(aIdentifier, "KB_CRAFTY_TOGGLE") == 0) {
        // Toggle window visibility
        g_WindowVisible = !g_WindowVisible;
        APIDefs->Log(LOGL_INFO, "CraftyLegend", g_WindowVisible ? "Window shown" : "Window hidden");
        return;
    }
}
